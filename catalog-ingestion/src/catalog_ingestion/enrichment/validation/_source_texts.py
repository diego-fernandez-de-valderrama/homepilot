from dataclasses import dataclass

from catalog_ingestion.core import TextNormalizer
from catalog_ingestion.enrichment.validation._quote_matcher import QuoteMatcher
from catalog_ingestion.models import NormalizedProduct, WebPage
from catalog_ingestion.vocabulary import FactSource


@dataclass(frozen=True, slots=True)
class SourceTexts:
    """The texts the LLM saw, normalized for evidence checks: an LLM claim is only accepted when its
    quote is found in the source it cites (or the other one)."""

    catalog: str
    web: str
    web_url: str | None
    web_method: str | None = None  # "http" or "gemini_url_context" (page text generated by a model)
    catalog_lines: str = ""  # normalized, line breaks kept (sentence and clause boundaries)
    web_lines: str = ""

    @classmethod
    def build(cls, product: NormalizedProduct, web_page: WebPage | None) -> "SourceTexts":
        web_ok = web_page is not None and web_page.ok
        catalog = cls.catalog_text(product)
        web = web_page.text if web_ok and web_page else ""
        return cls(
            catalog=TextNormalizer.normalize(catalog),
            web=TextNormalizer.normalize(web),
            web_url=web_page.url if web_ok and web_page else None,
            web_method=web_page.method if web_ok and web_page else None,
            catalog_lines=TextNormalizer.normalize_lines(catalog),
            web_lines=TextNormalizer.normalize_lines(web),
        )

    @staticmethod
    def catalog_text(product: NormalizedProduct) -> str:
        """All catalog strings the LLM saw, in the same `Key: Value` form used in the prompt."""
        parts = [
            product.title,
            product.subtitle,
            *product.variants,
            *product.description.highlights,
            product.description.text,
        ]
        parts.extend(product.attributes.badges)
        parts.extend(f"{entry.key}: {entry.value}" for entry in product.attributes.entries)
        parts.extend(product.attributes.unparsed_lines)
        if product.category_slug:
            parts.append(product.category_slug)
        return "\n".join(part for part in parts if part)

    def text_for(self, source: FactSource) -> str:
        return self.web if source is FactSource.WEB else self.catalog

    def lines_for(self, source: FactSource) -> str:
        return self.web_lines if source is FactSource.WEB else self.catalog_lines

    def locate(self, quote: str, cited: FactSource) -> FactSource | None:
        """Source that contains `quote`: the cited one first, then the other one."""
        for source in (cited, FactSource.WEB if cited is FactSource.CATALOG else FactSource.CATALOG):
            if QuoteMatcher.found(quote, self.text_for(source)):
                return source
        return None
