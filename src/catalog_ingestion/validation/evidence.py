"""Evidence verification: an LLM claim is only accepted when its quote is found in the source
it cites."""

import re
from dataclasses import dataclass

from catalog_ingestion.domain.enrichment import WebPage
from catalog_ingestion.domain.enums import FactSource
from catalog_ingestion.domain.product import NormalizedProduct

# Typographic quotes, en/em dashes and non-breaking spaces are folded to ASCII before matching.
_TRANSLATION = str.maketrans(
    {
        "\u201e": '"',
        "\u201c": '"',
        "\u201d": '"',
        "\u201a": "'",
        "\u2018": "'",
        "\u2019": "'",
        "\u2013": "-",
        "\u2014": "-",
        "\u00a0": " ",
    }
)
_WHITESPACE = re.compile(r"\s+")
_ELLIPSIS = re.compile(r"\.\.\.|…")
_EDGE_PUNCTUATION = " \"'.,;:!?()[]"
MIN_QUOTE_LENGTH = 3


def normalize_text(text: str) -> str:
    return _WHITESPACE.sub(" ", text.translate(_TRANSLATION)).strip().casefold()


def catalog_text(product: NormalizedProduct) -> str:
    """All catalog strings the LLM saw, in the same `Key: Value` form used in the prompt."""
    parts = [
        product.title,
        product.subtitle,
        *product.variants,
        *product.description.highlights,
        product.description.text,
    ]
    parts.extend(product.attributes.badges)
    parts.extend(f"{entry.key}: {entry.value}" for entry in product.attributes.entries)
    parts.extend(product.attributes.unparsed_lines)
    if product.category_slug:
        parts.append(product.category_slug)
    return "\n".join(part for part in parts if part)


@dataclass(frozen=True, slots=True)
class SourceTexts:
    catalog: str
    web: str
    web_url: str | None
    web_method: str | None = None  # "http" or "gemini_url_context" (page text generated by a model)

    @classmethod
    def build(cls, product: NormalizedProduct, web_page: WebPage | None) -> "SourceTexts":
        web_ok = web_page is not None and web_page.ok
        return cls(
            catalog=normalize_text(catalog_text(product)),
            web=normalize_text(web_page.text) if web_ok and web_page else "",
            web_url=web_page.url if web_ok and web_page else None,
            web_method=web_page.method if web_ok and web_page else None,
        )

    def text_for(self, source: FactSource) -> str:
        return self.web if source is FactSource.WEB else self.catalog

    def locate(self, quote: str, cited: FactSource) -> FactSource | None:
        """Source that contains `quote`: the cited one first, then the other one."""
        for source in (cited, FactSource.WEB if cited is FactSource.CATALOG else FactSource.CATALOG):
            if quote_found(quote, self.text_for(source)):
                return source
        return None


def _fragments(quote: str) -> list[str]:
    fragments = [normalize_text(fragment).strip(_EDGE_PUNCTUATION) for fragment in _ELLIPSIS.split(quote)]
    return [fragment for fragment in fragments if fragment]


def quote_found(quote: str, normalized_source: str) -> bool:
    if not normalized_source:
        return False
    fragments = _fragments(quote)
    if not fragments or sum(len(fragment) for fragment in fragments) < MIN_QUOTE_LENGTH:
        return False
    return all(fragment in normalized_source for fragment in fragments)


# Surface forms that are also everyday words ("matter Lack" = matte finish, "Ring" = ring) only count
# in their capitalized brand spelling.
_CASE_SENSITIVE_FORMS = frozenset({"matter", "ring"})


def _form_pattern(form: str) -> re.Pattern[str]:
    return re.compile(rf"(?<!\w){re.escape(form)}(?!\w)")


def mentions_any(text: str, forms: tuple[str, ...]) -> bool:
    """True when `text` names one of `forms` as a whole word ("lan" does not match inside "WLAN")."""
    normalized = normalize_text(text)
    folded_raw = _WHITESPACE.sub(" ", text.translate(_TRANSLATION))
    for form in forms:
        key = normalize_text(form)
        if not key:
            continue
        if key in _CASE_SENSITIVE_FORMS:
            capitalized = re.compile(rf"(?<!\w)({re.escape(key.capitalize())}|{re.escape(key.upper())})(?!\w)")
            if capitalized.search(folded_raw):
                return True
        elif _form_pattern(key).search(normalized):
            return True
    return False


_SENTENCE_END = re.compile(r"[.!?;\n]\s")
# Negation words (DE/EN). "kein" also covers keine/keinen/keiner.
_NEGATION = re.compile(r"(?<!\w)(kein\w*|ohne|nicht|weder|no|not|non|without|never|nie)(?!\w)")
NEGATION_WINDOW = 40


def quote_sentence(quote: str, normalized_source: str) -> str | None:
    """The sentence(s) of the source that contain the quote, or None when it is not found."""
    fragments = _fragments(quote)
    if not fragments:
        return None
    start = normalized_source.find(fragments[0])
    if start < 0:
        return None
    end_fragment = normalized_source.find(fragments[-1], start)
    end = (end_fragment if end_fragment >= 0 else start) + len(fragments[-1])
    before = [match.end() for match in _SENTENCE_END.finditer(normalized_source, 0, start)]
    sentence_start = before[-1] if before else 0
    after = _SENTENCE_END.search(normalized_source, end)
    return normalized_source[sentence_start : after.start() + 1 if after else len(normalized_source)]


def negation_near(quote: str, normalized_source: str) -> bool:
    """True when the quote, or the same sentence up to NEGATION_WINDOW characters before it, negates
    ("Funktioniert ganz ohne Gateway", "Kein HUB erforderlich", "nicht kompatibel mit ...")."""
    fragments = _fragments(quote)
    if not fragments:
        return False
    if any(_NEGATION.search(fragment) for fragment in fragments):
        return True
    start = normalized_source.find(fragments[0])
    if start < 0:
        return False
    before = [match.end() for match in _SENTENCE_END.finditer(normalized_source, 0, start)]
    window_start = max(before[-1] if before else 0, start - NEGATION_WINDOW)
    return bool(_NEGATION.search(normalized_source[window_start:start]))
