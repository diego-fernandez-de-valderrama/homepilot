"""Evidence verification: an LLM claim is only accepted when its quote is found in the source
it cites."""

import re
from dataclasses import dataclass

from catalog_ingestion.domain.enrichment import WebPage
from catalog_ingestion.domain.enums import FactSource
from catalog_ingestion.domain.product import NormalizedProduct

# Typographic quotes, en/em dashes and non-breaking spaces are folded to ASCII before matching.
_TRANSLATION = str.maketrans(
    {
        "\u201e": '"',
        "\u201c": '"',
        "\u201d": '"',
        "\u201a": "'",
        "\u2018": "'",
        "\u2019": "'",
        "\u2013": "-",
        "\u2014": "-",
        "\u00a0": " ",
    }
)
_WHITESPACE = re.compile(r"\s+")
_ELLIPSIS = re.compile(r"\.\.\.|…")
_EDGE_PUNCTUATION = " \"'.,;:!?()[]"
MIN_QUOTE_LENGTH = 3


def normalize_text(text: str) -> str:
    return _WHITESPACE.sub(" ", text.translate(_TRANSLATION)).strip().casefold()


def catalog_text(product: NormalizedProduct) -> str:
    """All catalog strings the LLM saw, in the same `Key: Value` form used in the prompt."""
    parts = [
        product.title,
        product.subtitle,
        *product.variants,
        *product.description.highlights,
        product.description.text,
    ]
    parts.extend(product.attributes.badges)
    parts.extend(f"{entry.key}: {entry.value}" for entry in product.attributes.entries)
    parts.extend(product.attributes.unparsed_lines)
    if product.category_slug:
        parts.append(product.category_slug)
    return "\n".join(part for part in parts if part)


@dataclass(frozen=True, slots=True)
class SourceTexts:
    catalog: str
    web: str
    web_url: str | None
    web_method: str | None = None  # "http" or "gemini_url_context" (page text generated by a model)
    catalog_lines: str = ""  # normalized, line breaks kept (sentence and clause boundaries)
    web_lines: str = ""

    @classmethod
    def build(cls, product: NormalizedProduct, web_page: WebPage | None) -> "SourceTexts":
        web_ok = web_page is not None and web_page.ok
        catalog = catalog_text(product)
        web = web_page.text if web_ok and web_page else ""
        return cls(
            catalog=normalize_text(catalog),
            web=normalize_text(web),
            web_url=web_page.url if web_ok and web_page else None,
            web_method=web_page.method if web_ok and web_page else None,
            catalog_lines=normalize_lines(catalog),
            web_lines=normalize_lines(web),
        )

    def text_for(self, source: FactSource) -> str:
        return self.web if source is FactSource.WEB else self.catalog

    def lines_for(self, source: FactSource) -> str:
        return self.web_lines if source is FactSource.WEB else self.catalog_lines

    def locate(self, quote: str, cited: FactSource) -> FactSource | None:
        """Source that contains `quote`: the cited one first, then the other one."""
        for source in (cited, FactSource.WEB if cited is FactSource.CATALOG else FactSource.CATALOG):
            if quote_found(quote, self.text_for(source)):
                return source
        return None


def _fragments(quote: str) -> list[str]:
    fragments = [normalize_text(fragment).strip(_EDGE_PUNCTUATION) for fragment in _ELLIPSIS.split(quote)]
    return [fragment for fragment in fragments if fragment]


def quote_found(quote: str, normalized_source: str) -> bool:
    if not normalized_source:
        return False
    fragments = _fragments(quote)
    if not fragments or sum(len(fragment) for fragment in fragments) < MIN_QUOTE_LENGTH:
        return False
    return all(fragment in normalized_source for fragment in fragments)


def _form_pattern(form: str) -> re.Pattern[str]:
    return re.compile(rf"(?<!\w){re.escape(form)}(?!\w)")


def forms_pattern(forms: tuple[str, ...]) -> re.Pattern[str]:
    """One whole-word pattern over normalized text for several surface forms."""
    keys = sorted({normalize_text(form) for form in forms if normalize_text(form)}, key=len, reverse=True)
    return re.compile(rf"(?<!\w)(?:{'|'.join(map(re.escape, keys))})(?!\w)" if keys else r"(?!x)x")


# "matter" is also the German adjective (matte finish): a lowercase "matter" followed by a capitalized word
# ("matter Lack", "matter Oberfläche") is that adjective. Titles use "... 1100 matter" and "matterkompatibel".
_MATTER = re.compile(
    r"(?<!\w)(?:Matter|MATTER)(?!\w)|(?<!\w)matter(?:kompatib|fähig|zertifi)|(?<!\w)matter(?!\w)(?!\s+[A-ZÄÖÜ])"
)


def mentions_any(text: str, forms: tuple[str, ...]) -> bool:
    """True when `text` names one of `forms` as a whole word ("lan" does not match inside "WLAN")."""
    normalized = normalize_text(text)
    folded_raw = _WHITESPACE.sub(" ", text.translate(_TRANSLATION))
    for form in forms:
        key = normalize_text(form)
        if not key:
            continue
        if key == "matter":
            if _MATTER.search(folded_raw):
                return True
        elif _form_pattern(key).search(normalized):
            return True
    return False


def normalize_lines(text: str) -> str:
    """Like `normalize_text`, but keeps line breaks (attribute lines, paragraphs) as boundaries."""
    return "\n".join(line for line in (normalize_text(line) for line in text.splitlines()) if line)


_SENTENCE_END = re.compile(r"\n|[.!?;](?=\s)")
_CLAUSE_BOUNDARY = re.compile(r"[\n,;:()\[\]]|[.!?](?=\s|$)|\s[-–]\s")
# Negation words (DE/EN). "kein" also covers keine/keinen/keiner; "not" never as German "Not-" (emergency).
_NEGATION = re.compile(r"^(kein\w*|ohne|nicht|weder|no|not|non|without|never|nie)$")
_NEGATION_AFTER = re.compile(r"^(nicht|not)$")
# "(nicht enthalten)", "nicht im Lieferumfang enthalten", "not included" say what is in the box, not
# whether something is needed or compatible.
_NOT_INCLUDED = re.compile(r"nicht (?:im lieferumfang )?(?:enthalten|inbegriffen)|nicht im lieferumfang|not included")
_WORD_TOKEN = re.compile(r"[\w+-]+")
NEGATION_WORDS = 3


def _locate(quote: str, lines_text: str) -> tuple[int, int] | None:
    fragments = _fragments(quote)
    if not fragments:
        return None
    start = lines_text.find(fragments[0])
    if start < 0:
        return None
    end_fragment = lines_text.find(fragments[-1], start)
    return start, (end_fragment if end_fragment >= 0 else start) + len(fragments[-1])


def quote_sentence(quote: str, lines_text: str) -> str | None:
    """The sentence(s) of the source (normalized with `normalize_lines`) that contain the quote."""
    span = _locate(quote, lines_text)
    if span is None:
        return None
    start, end = span
    before = [match.end() for match in _SENTENCE_END.finditer(lines_text, 0, start)]
    after = _SENTENCE_END.search(lines_text, end)
    return lines_text[before[-1] if before else 0 : after.start() if after else len(lines_text)]


def mention_negated(
    mention: re.Pattern[str], quote: str, lines_text: str, max_words_before: int | None = NEGATION_WORDS
) -> bool:
    """True when a mention of the claimed term is negated in its own clause: a negation word up to
    NEGATION_WORDS words before it ("ohne Gateway", "Kein HUB erforderlich", "nicht kompatibel mit Apple
    HomeKit", "keine zusätzliche Bridge") or "nicht"/"not" right after it ("Hub nicht erforderlich").
    A negation elsewhere in the sentence ("..., wodurch kein weiterer Hub nötig ist") does not count.
    With `max_words_before=None` any negation earlier in the clause counts ("Nicht mehr kompatibel mit
    der Zentrale CCU2")."""
    span = _locate(quote, lines_text)
    if span is None:
        region = normalize_text(quote)
    else:
        start, end = span
        before = [match.end() for match in _CLAUSE_BOUNDARY.finditer(lines_text, 0, start)]
        after = _CLAUSE_BOUNDARY.search(lines_text, end)
        region = lines_text[before[-1] if before else 0 : after.start() if after else len(lines_text)]
    region = _NOT_INCLUDED.sub(" ", region)
    for clause in _CLAUSE_BOUNDARY.split(region):
        for match in mention.finditer(clause):
            words_before = _WORD_TOKEN.findall(clause[: match.start()])
            if max_words_before is not None:
                words_before = words_before[-max_words_before:]
            words_after = _WORD_TOKEN.findall(clause[match.end() :])[:NEGATION_WORDS]
            if any(_NEGATION.match(word) for word in words_before):
                return True
            if any(_NEGATION_AFTER.match(word) for word in words_after):
                return True
    return False
